import { readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { additionalIcons } from './icon-definitions.mjs';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(rootDir, 'src', 'icons');
const generatedMarker = '// Generated by scripts/generate-icons.mjs. Do not edit.\n';
const generatedNames = new Set(additionalIcons.flatMap(({ name }) => [`${name}.tsx`, `${name}.native.tsx`]));

for (const fileName of await readdir(iconsDir)) {
  if (!generatedNames.has(fileName)) continue;
  await rm(join(iconsDir, fileName));
}

await Promise.all(
  additionalIcons.flatMap(({ name, vendor }) => {
    const webSource = `${generatedMarker}import { ${vendor}Icon } from '@phosphor-icons/react/dist/csr/${vendor}';

import { createWebIcon } from './internal/createWebIcon';

export default createWebIcon(${vendor}Icon, '${name}');
`;
    const nativeSource = `${generatedMarker}import { ${vendor}Icon } from 'phosphor-react-native';

import { createNativeIcon } from './internal/createNativeIcon.native';

export default createNativeIcon(${vendor}Icon, '${name}');
`;

    return [
      writeFile(join(iconsDir, `${name}.tsx`), webSource),
      writeFile(join(iconsDir, `${name}.native.tsx`), nativeSource),
    ];
  }),
);

const webExports = additionalIcons
  .map(({ name }) => `export { default as ${name} } from './${name}';`)
  .join('\n');
const nativeExports = additionalIcons
  .map(({ name }) => `export { default as ${name} } from './${name}.native';`)
  .join('\n');

await Promise.all([
  writeFile(join(iconsDir, 'generated.ts'), `${generatedMarker}${webExports}\n`),
  writeFile(join(iconsDir, 'generated.native.ts'), `${generatedMarker}${nativeExports}\n`),
]);
